import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {createTikFinityAdapter} from '../tikfinity.mjs';
import {createGiftRules,giftDefaults} from '../gift-rules.mjs';
const catalog=JSON.parse(await readFile(new URL('../catalog.json',import.meta.url),'utf8'));
assert.equal(catalog.length,154);
for(const gift of catalog){assert(Number.isSafeInteger(gift.coins)&&gift.coins>0);await readFile(new URL('../'+gift.image,import.meta.url));}
const rules=createGiftRules(catalog),settings={...giftDefaults(),blueHealGift:'6064'};
assert.deepEqual(rules.validate(settings),settings);
assert.equal(rules.resolve('5655',1,settings).power,1,'one coin deals one damage');
assert.equal(rules.resolve('5655',20,settings).power,20,'combo multiplies coin value');
assert.equal(rules.resolve('6064',7,settings).type,'heal');
assert.equal(rules.resolve('6064',7,settings).power,7,'healing equals coin value × count');
const expensive=catalog.find(g=>g.coins>100);settings.redAttackGifts.push(expensive.id);
assert.equal(rules.resolve(expensive.id,2,settings).power,expensive.coins*2,'no old 12 damage or 100 coin cap');
assert.equal(rules.resolve('999999999',1,settings),null);
assert.equal(rules.resolve(catalog.find(g=>!['5655','5269','6064',expensive.id].includes(g.id)).id,1,settings),null);
assert.throws(()=>rules.validate({...settings,redHealGift:'5655'}),'one gift cannot affect both sides');
for(const n of [0,-1,1.5,NaN,100001])assert.throws(()=>rules.resolve('5655',n,settings));
const adapter=createTikFinityAdapter();
for(const event of ['chat','like','vote','punch','special','follow'])assert.deepEqual(adapter.receive({event,data:{comment:'1',likeCount:1000,userId:'viewer'}}),[],'only gifts affect the game');
const gift=extra=>({event:'gift',data:{giftId:5655,giftType:1,repeatCount:4,userId:'u',groupId:'combo1',msgId:'g1',...extra}});
assert.deepEqual(adapter.receive(gift({repeatEnd:false})),[]);
assert.deepEqual(adapter.receive(gift({repeatEnd:true})),[{giftId:'5655',count:4}]);
assert.deepEqual(adapter.receive(gift({repeatEnd:true,msgId:'g2'})),[],'completed combo counted once');
for(const msgId of ['single1','single2'])assert.deepEqual(adapter.receive(gift({giftType:0,groupId:'0',msgId,repeatCount:1})),[{giftId:'5655',count:1}]);
for(const invalid of [null,[],{}, {event:'gift',data:null},gift({msgId:'',groupId:'',repeatEnd:true}),gift({repeatEnd:true,repeatCount:-1}),gift({giftType:undefined})])assert.throws(()=>adapter.receive(invalid));
console.log('PASS: 154 catalog gifts/icons, exclusive assignments, exact coin damage/healing, gift-only events, combo completion and replay prevention.');
