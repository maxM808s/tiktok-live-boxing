// Synthetic fixtures based on TikFinity's Event API and the connector event docs.
import assert from 'node:assert/strict';
import {createTikFinityAdapter} from '../tikfinity.mjs';
const a=createTikFinityAdapter();
const chat=(comment,extra={})=>({event:'chat',data:{uniqueId:'viewer',comment,...extra}});
const like=(count,extra={})=>({event:'like',data:{uniqueId:'viewer',likeCount:count,...extra}});
const gift=extra=>({event:'gift',data:{uniqueId:'viewer',giftId:100,giftType:1,repeatCount:3,groupId:'combo-1',...extra}});
assert.deepEqual(a.receive(like(20)),[],'unassigned likes ignored');
assert.deepEqual(a.receive(gift({repeatEnd:true})),[],'unassigned gifts ignored');
assert.deepEqual(a.receive(chat('not a team')),[]);
assert.deepEqual(a.receive(chat(' 1 ',{msgId:'c1'})),[{type:'vote',side:'blue',count:1}]);
assert.deepEqual(a.receive(chat('1',{msgId:'c1'})),[],'duplicate chat ignored');
assert.deepEqual(a.receive(like(9,{msgId:'l1'})),[]);
assert.deepEqual(a.receive(like(21,{msgId:'l2'})),[{type:'vote',side:'blue',count:3}]);
assert.deepEqual(a.receive(like(21,{msgId:'l2'})),[],'like batch not counted twice');
assert.deepEqual(a.receive(gift({groupId:'combo-2',repeatEnd:false,msgId:'g1'})),[]);
assert.deepEqual(a.receive(gift({groupId:'combo-2',repeatEnd:true,msgId:'g1'})),[{type:'gift',side:'blue',count:3}]);
assert.deepEqual(a.receive(gift({groupId:'combo-2',repeatEnd:true,msgId:'g2'})),[],'final combo not counted twice even with a new message ID');
assert.deepEqual(a.receive(chat('2')),[{type:'vote',side:'red',count:1}]);
assert.deepEqual(a.receive({event:'gift',data:{uniqueId:'viewer',giftType:0,repeatCount:1,msgId:'single'}}),[{type:'gift',side:'red',count:1}]);
assert.deepEqual(a.receive({event:'chat',data:{user:{userId:'stable-id',uniqueId:'nested'},comment:'1'}}),[{type:'vote',side:'blue',count:1}]);
assert.deepEqual(a.receive({event:'like',data:{user:{userId:'stable-id',uniqueId:'renamed'},likeCount:10}}),[{type:'vote',side:'blue',count:1}]);
assert.deepEqual(a.receive({event:'like',data:{userId:'stable-id',likeCount:-1}}),[],'negative likes ignored');
for(const msgId of ['single2','single3'])assert.deepEqual(a.receive({event:'gift',data:{uniqueId:'viewer',giftType:0,groupId:'0',msgId}}),[{type:'gift',side:'red',count:1}]);
assert.deepEqual(a.receive(chat('1',{roomId:'room1',msgId:'room-chat'})),[{type:'vote',side:'blue',count:1}]);
assert.deepEqual(a.receive(like(10,{msgId:'no-room-like'})),[{type:'vote',side:'blue',count:1}]);
assert.deepEqual(a.receive({event:'follow',data:{}}),[]);
for(const invalid of [null,[],{}, {event:'chat',data:null},{type:'vote',side:'blue'}])assert.throws(()=>a.receive(invalid));
a.reset();assert.deepEqual(a.receive(like(20)),[]);
console.log('PASS: TikFinity envelope, team selection, batched likes, completed gift combos, flat/nested users, deduplication and invalid payloads.');
